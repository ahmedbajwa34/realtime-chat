export interface ClientMessagePayload {
    clientMsgId: string;   // UUID generated by the client, used for idempotent retries
    to?: string;
    text: string;
}

export interface ServerMessagePayload {
    id: string;
    from: string;
    text: string;
    createdAt: Date;       // arrives as an ISO string on the client
    private: boolean;
    room?: string;
}

export type MessageAck =
    | {
          ok: true;
          target: "private";
          recipient: string;
          id: string;
          createdAt: Date;
          status: "sent";
      }
    | {
          ok: true;
          target: "room";
          room: string;
          id: string;
          createdAt: Date;
      }
    | {
          ok: false;
          error:
              | "REGISTER_REQUIRED"
              | "INVALID_MESSAGE"
              | "RECIPIENT_NOT_FOUND"
              | "NOT_IN_ROOM"
              | "DATABASE_ERROR";
          message: string;
      };

export interface MessageStatusPayload {
    id: string;
    status: "delivered" | "read";
    deliveredAt?: Date;
    readAt?: Date;
}

export interface ClientToServerEvents {
    register: (name: unknown) => void;
    "join-room": (room: unknown) => void;
    message: (
        data: unknown,
        acknowledge: (result: MessageAck) => void
    ) => void;
    "private-history": (
        otherUsername: unknown,
        acknowledge: (result: PrivateHistoryAck) => void
    ) => void;
    "message-delivered": (
        messageId: unknown,
        acknowledge: (result: DeliveryAck) => void
    ) => void;
}

export interface ServerToClientEvents {
    message: (data: ServerMessagePayload) => void;
    system: (text: string) => void;
    "room-history": (messages: RoomHistoryMessage[]) => void;
    "current-user": (user: { id: string; username: string }) => void;
    "presence-snapshot": (usernames: string[]) => void;
    "user-status": (data: {
        username: string;
        status: "online" | "offline";
    }) => void;
    "message-status": (data: MessageStatusPayload) => void;
}

export interface RoomHistoryMessage {
    id: string;
    sender_username: string;
    room_name: string | null;   // was `string`; StoredMessage uses string | null
    content: string;
    created_at: Date;
}

export interface PrivateHistoryMessage {
    id: string;
    sender_username: string;
    recipient_username: string | null;
    room_name: string | null;
    content: string;
    created_at: Date;
    delivered_at: Date | null;   // the frontend uses these to render ticks
    read_at: Date | null;
}

export type PrivateHistoryAck =
    | { ok: true; messages: PrivateHistoryMessage[] }
    | { ok: false; message: string };

export type DeliveryAck =
    | { ok: true; messageId: string }
    | {
          ok: false;
          error: "INVALID_MESSAGE_ID" | "MESSAGE_NOT_FOUND";
          message: string;
      };